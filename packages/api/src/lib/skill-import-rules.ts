import {
  SKILL_FILE_MAX_DEPTH,
  SKILL_FILE_PATH_MAX_LENGTH,
  SKILL_FILE_PATH_PATTERN,
} from "../validations/skills";

/**
 * What a skill zip import leaves out before anything counts toward the
 * skill's caps, and the terminal check that recomputes an imported skill's
 * fingerprint on its source folder. The import and the check both read the
 * one table below, so a new rule reaches both, and the importer's tests run
 * the check on a real folder holding a file for every rule. Pure and
 * client-safe: the dashboard builds the check too.
 */

interface LeaveOutRule {
  /** What the import reports for each file left out. */
  reason: string;
  /** A file under a folder of one of these names (exact case), any depth. */
  folders: readonly string[];
  /** A file named like one of these, any case. `*` (any characters) is the
   * only wildcard: the same glob runs in `find -iname`. */
  files: readonly string[];
}

/** First match wins. Hidden names are refused by the path rule anyway; they
 * are listed so the person reads the specific reason. */
export const SKILL_LEAVE_OUT_RULES: readonly LeaveOutRule[] = [
  {
    // Tool and OS state, as a folder or as a file of that name (a
    // submodule's .git is a file).
    reason: "System file",
    folders: ["__MACOSX", ".git", "node_modules"],
    files: [
      "__MACOSX",
      ".git",
      "node_modules",
      ".DS_Store",
      "Thumbs.db",
      "desktop.ini",
      "._*",
    ],
  },
  {
    // Regenerated by a tool on its own: a vendored library's __pycache__
    // alone can double its file count and crowd real files out of the cap.
    reason: "Generated file",
    folders: [
      "__pycache__",
      ".venv",
      "venv",
      ".pytest_cache",
      ".mypy_cache",
      ".ruff_cache",
      ".tox",
      ".idea",
      ".vscode",
    ],
    files: ["*.pyc", "*.pyo", "*.swp"],
  },
  {
    // A skill is shared content: credentials reach the agent through the
    // gateway, never as files in its skills.
    reason: "Possible secrets file",
    folders: [],
    files: [".env", ".env.*"],
  },
];

const escapeRegExp = (text: string): string =>
  text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const COMPILED_RULES = SKILL_LEAVE_OUT_RULES.map((rule) => ({
  reason: rule.reason,
  folders: new Set(rule.folders),
  files: rule.files.map(
    (glob) =>
      new RegExp(`^${glob.split("*").map(escapeRegExp).join(".*")}$`, "i"),
  ),
}));

/** Why the import leaves out the file at `path` ("/" separated), or null. */
export const skillLeaveOutReason = (path: string): string | null => {
  const folders = path.split("/");
  const name = folders.pop() ?? "";
  const rule = COMPILED_RULES.find(
    (r) =>
      folders.some((folder) => r.folders.has(folder)) ||
      r.files.some((pattern) => pattern.test(name)),
  );
  return rule?.reason ?? null;
};

/** An imported skill's fingerprint: lowercase hex sha256. */
export const SKILL_FINGERPRINT_PATTERN = /^[0-9a-f]{64}$/;

/** SKILL_FILE_PATH_PATTERN as find globs: no path segment starting with
 * anything but a letter, digit or underscore (hidden names included), and
 * no character outside letters, digits, ".", "_", "-" and "/". A change to
 * the pattern fails the importer's check-command test until this follows. */
const PATH_RULE_CLAUSES = [
  "! -path '*/[!A-Za-z0-9_]*'",
  "! -path '*[!A-Za-z0-9._/-]*'",
];

/** A name the path rule already refuses needs no clause of its own. */
const pathRuleAllows = (name: string): boolean =>
  SKILL_FILE_PATH_PATTERN.test(name.replaceAll("*", "x"));

/** sha256 in shasum's listing format, of files or stdin: Linux ships
 * sha256sum, older macOS only shasum. */
const SHA256 = `sh -c 'if command -v sha256sum >/dev/null; then sha256sum "$@"; else shasum -a 256 "$@"; fi' sh`;

/**
 * A command to paste in a terminal inside a skill's source folder (sh, bash
 * or zsh, on macOS or Linux): it recomputes the fingerprint the way the
 * import does, over the files the import keeps, and says whether the folder
 * matches.
 *
 * What it can't see is what the zip tool or the zip itself decided: a
 * symbolic link stored as a file, files that differ only in case, and
 * entries the import reported as damaged or unreadable. Any of those makes
 * an untouched folder read as different.
 */
export const skillCheckCommand = (fingerprint: string): string => {
  // Only hex reaches the command: it is pasted into a shell.
  if (!SKILL_FINGERPRINT_PATTERN.test(fingerprint)) {
    throw new Error("skillCheckCommand takes a sha256 fingerprint");
  }
  const leaveOut = SKILL_LEAVE_OUT_RULES.flatMap((rule) => [
    ...rule.folders.filter(pathRuleAllows).map((f) => `! -path '*/${f}/*'`),
    ...rule.files.filter(pathRuleAllows).map((f) => `! -iname '${f}'`),
  ]);
  return [
    [
      `LC_ALL=C find . -maxdepth ${SKILL_FILE_MAX_DEPTH} -type f`,
      ...PATH_RULE_CLAUSES,
      ...leaveOut,
    ].join(" "),
    "cut -c3-",
    `LC_ALL=C awk 'length($0) <= ${SKILL_FILE_PATH_MAX_LENGTH}'`,
    "LC_ALL=C sort",
    "tr '\\n' '\\0'",
    `xargs -0 ${SHA256}`,
    SHA256,
    "cut -c1-64",
    `grep -qx ${fingerprint} && echo "Matches the imported skill" || echo "Doesn't match the imported skill"`,
  ].join(" | ");
};
